"""Privacy disclosures served from the API.

The SPA renders /privacy, but the facts live here so the page cannot drift
from what the deployment actually does — in particular *which* third-party
LLM a self-hosted instance is shipping CV text to, which is an env var, not
a copywriting decision.
"""

from __future__ import annotations

from fastapi import APIRouter

from gosha.services.cv import MAX_CV_BYTES

router = APIRouter(prefix="/legal", tags=["legal"])

# Kept next to the code that does the sending, so it is obvious when a new
# egress is added: gosha/cover_letter.py truncates the CV to CV_CHARS_TO_LLM
# characters and posts it to whichever provider gosha/llm.py selects.
_PROVIDER_DETAILS = {
    "openrouter": {
        "name": "OpenRouter",
        "operator": "OpenRouter, Inc. (United States)",
        "url": "https://openrouter.ai/privacy",
        "note": (
            "OpenRouter routes the request on to the model vendor configured "
            "in OPENROUTER_MODEL."
        ),
    },
    "gemini": {
        "name": "Google Gemini API",
        "operator": "Google Ireland Ltd / Google LLC",
        "url": "https://ai.google.dev/gemini-api/terms",
        "note": "Requests are sent to the Gemini generateContent endpoint.",
    },
}


